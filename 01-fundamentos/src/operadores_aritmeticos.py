produto_1 = 20
produto_2 = 10

# Adição
print(f"Adição: {produto_1} + {produto_2} = {produto_1 + produto_2}")

# Subtração
print(f"Subtração: {produto_1} - {produto_2} = {produto_1 - produto_2}")

# Multiplicação
print(f"Multiplicação: {produto_1} * {produto_2} = {produto_1 * produto_2}")

# Divisão Real (retorna float)
print(f"Divisão Real: {produto_1} / {produto_2} = {produto_1 / produto_2}")

# Divisão Inteira (retorna int)
print(f"Divisão Inteira: {produto_1} // {produto_2} = {produto_1 // produto_2}")

# Módulo (Resto da divisão)
print(f"Módulo: 10 % 3 = {10 % 3}")

# Exponenciação (Potência)
print(f"Exponenciação: 2 ** 3 = {2**3}")

# Ordem de Precedência (Parênteses > Expoentes > Multiplicação/Divisão > Soma/Subtração)
calculo = 10 - 5 * 2 + (10 / 2)
print(f"Ordem de Precedência: 10 - 5 * 2 + (10 / 2) = {calculo}")
