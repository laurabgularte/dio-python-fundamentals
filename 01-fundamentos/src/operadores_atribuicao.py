# Atribuição simples
saldo = 500
print(f"Saldo inicial: {saldo}")

# Atribuição com adição (saldo = saldo + 200)
saldo += 200
print(f"Após saldo += 200: {saldo}")

# Atribuição com subtração (saldo = saldo - 100)
saldo -= 100
print(f"Após saldo -= 100: {saldo}")

# Atribuição com multiplicação (saldo = saldo * 2)
saldo *= 2
print(f"Após saldo *= 2: {saldo}")

# Atribuição com divisão (saldo = saldo / 2)
saldo /= 2
print(f"Após saldo /= 2: {saldo}")

# Atribuição com divisão inteira e módulo
saldo //= 3
print(f"Após saldo //= 3: {saldo}")

saldo %= 3
print(f"Após saldo %= 3: {saldo}")

# Exponenciação atribuída
numero = 2
numero **= 3
print(f"2 elevado ao cubo (numero **= 3): {numero}")
